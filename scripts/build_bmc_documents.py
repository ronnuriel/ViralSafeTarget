def count_abstract_words() -> int:
    source = SOURCE.read_text()
    abstract = source.split("## Abstract", 1)[1].split("**Keywords:**", 1)[0]
    abstract = re.sub(r"^#+\s*", "", abstract, flags=re.M)
    return len(re.findall(r"\b[\w–-]+\b", abstract))


def main():
    FINAL.mkdir(parents=True, exist_ok=True)
    for figure in [*(FIGURES.glob("Figure_*.pdf")), *(FIGURES.glob("Figure_*.png"))]:
        if figure.stat().st_size >= 10 * 1024 * 1024:
            raise AssertionError(f"Figure exceeds 10 MB: {figure}")
    count = count_abstract_words()
    if count > 350:
        raise AssertionError(f"Abstract is {count} words; BMC limit is 350")
    build_manuscript()
    build_admin_files()
    build_review_queue()
    build_text_admin()
    build_additional_files()
    (FINAL / "build_metadata.json").write_text(
        json.dumps(
            {
                "status": "DO NOT SUBMIT",
                "abstract_word_count": count,
                "frozen_source_commit": FROZEN_COMMIT,
                "build_date": date.today().isoformat(),
                "human_review_resolved": 0,
                "human_review_pending": len(pd.read_csv(FINAL / "HUMAN_REVIEW_REQUIRED.csv")),
            },
            indent=2,
        )
        + "\n"
    )
    print(f"Built BMC working package; abstract words={count}")


