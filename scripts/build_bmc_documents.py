def build_manuscript() -> Path:
    source = SOURCE.read_text(encoding="utf-8")
    doc = Document()
    _configure_document(doc, double_spaced=True, line_numbers=True)

    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(18)
    p.paragraph_format.space_after = Pt(12)
    run = p.add_run(ARTICLE_TITLE)
    _font(run, size=16, bold=True)
    for line, size, bold in (
        ("Software Article — BMC Bioinformatics", 12, True),
        ("DO NOT SUBMIT — HUMAN REVIEW PENDING", 12, True),
        ("Ron Nuriel¹*", 12, False),
        ("¹[AFFILIATION REQUIRED]", 11, False),
        ("*Correspondence: [EMAIL REQUIRED]", 11, False),
    ):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_after = Pt(4)
        color = (180, 35, 24) if "DO NOT SUBMIT" in line else None
        run = p.add_run(line)
        _font(run, size=size, bold=bold, color=color)

    # Skip source title-page metadata; start parsing at Abstract.
    lines = source.splitlines()
    start = next(i for i, line in enumerate(lines) if line == "## Abstract")
    paragraph_buffer: list[str] = []

    def flush():
        if not paragraph_buffer:
            return
        text = " ".join(x.strip() for x in paragraph_buffer).strip()
        paragraph_buffer.clear()
        if text:
            p = doc.add_paragraph()
            p.paragraph_format.widow_control = True
            _add_rich_text(p, text)

    current_h2 = ""
    for line in lines[start:]:
        if not line.strip():
            flush()
            continue
        if line.startswith("## "):
            flush()
            current_h2 = line[3:].strip()
            doc.add_heading(current_h2, level=1)
            continue
        if line.startswith("### "):
            flush()
            heading = line[4:].strip()
            doc.add_heading(heading, level=2)
            if current_h2 == "Results":
                _publication_tables(doc, heading)
            continue
        if line.startswith("- "):
            flush()
            p = doc.add_paragraph(style="List Bullet")
            p.paragraph_format.left_indent = Inches(0.5)
            p.paragraph_format.first_line_indent = Inches(-0.25)
            p.paragraph_format.keep_together = True
            _add_rich_text(p, line[2:])
            continue
        if current_h2 == "References" and re.match(r"^\d+\.\s", line):
            flush()
            p = doc.add_paragraph()
            p.paragraph_format.left_indent = Inches(0.25)
            p.paragraph_format.first_line_indent = Inches(-0.25)
            p.paragraph_format.keep_together = True
            _add_rich_text(p, line)
            continue
        paragraph_buffer.append(line)
    flush()

    output = FINAL / "Main_Manuscript_BMC_Bioinformatics.docx"
    FINAL.mkdir(parents=True, exist_ok=True)
    doc.save(output)
    shutil.copy2(SOURCE, FINAL / "Main_Manuscript_BMC_Bioinformatics.md")
    return output


def _build_simple_doc(path, title, paragraphs, *, letter=False):
    doc = Document()
    _configure_document(doc, double_spaced=not letter, line_numbers=False)
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER if not letter else WD_ALIGN_PARAGRAPH.LEFT
    run = p.add_run(title)
    _font(run, size=15, bold=True)
    for text in paragraphs:
        p = doc.add_paragraph()
        p.paragraph_format.line_spacing = 1.15 if letter else 2
        _add_rich_text(p, text)
    doc.save(path)


